-- 1. Crear tabla CANCHAS
CREATE TABLE CANCHAS (
    numero_cancha NUMBER PRIMARY KEY,          
    tipo_cancha   VARCHAR2(20) NOT NULL,       
    precio_base   NUMBER NOT NULL,             
    estado        VARCHAR2(15) DEFAULT 'Activa'
);

-- 2. Crear tabla RESERVAS 
CREATE TABLE RESERVAS (
    id_reserva    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
    fecha_reserva VARCHAR2(10) NOT NULL,       
    hora_reserva  VARCHAR2(5) NOT NULL,        
    numero_cancha NUMBER NOT NULL,             
    jugadores     VARCHAR2(150) NOT NULL,      
    precio_total  NUMBER NOT NULL,             
    CONSTRAINT fk_cancha FOREIGN KEY (numero_cancha) REFERENCES CANCHAS(numero_cancha)
);

