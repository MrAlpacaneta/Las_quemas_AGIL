-- 1. Crear tabla CANCHAS (Módulo 1.3 CRUD de Canchas)
CREATE TABLE CANCHAS (
    numero_cancha NUMBER PRIMARY KEY,          -- Ej: 1, 2, 3 (Identificador único)[cite: 1, 23]
    tipo_cancha   VARCHAR2(20) NOT NULL,       -- 'Padel' o 'Futbol'[cite: 1, 23]
    precio_base   NUMBER NOT NULL,             -- Precio por bloque horario[cite: 1, 23]
    estado        VARCHAR2(15) DEFAULT 'Activa'-- 'Activa' o 'Inactiva' (Borrado lógico)
);

-- 2. Crear tabla RESERVAS (Módulo 1.1 Reservas)[cite: 25]
CREATE TABLE RESERVAS (
    id_reserva    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID correlativo automático
    fecha_reserva VARCHAR2(10) NOT NULL,       -- Formato DD/MM/AAAA[cite: 1, 23]
    hora_reserva  VARCHAR2(5) NOT NULL,        -- Formato HH:MM (Ej: '19:00')[cite: 1, 23]
    numero_cancha NUMBER NOT NULL,             -- Cancha asignada[cite: 1, 23]
    jugadores     VARCHAR2(150) NOT NULL,      -- Nombres de los jugadores[cite: 1, 23]
    precio_total  NUMBER NOT NULL,             -- Monto a cobrar[cite: 1, 23]
    CONSTRAINT fk_cancha FOREIGN KEY (numero_cancha) REFERENCES CANCHAS(numero_cancha)
);

